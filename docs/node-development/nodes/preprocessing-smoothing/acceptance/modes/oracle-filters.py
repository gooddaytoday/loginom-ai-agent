"""Independent filter-bank proposals, Python stdlib only; no Loginom/actual input.

Stdlib port (decision 6 of LAB-1119) of the former numpy/PyWavelets 1.9.0
oracle. The six expected-*.json files were generated by that oracle; --check
compares them with this port by tolerance, never by exact JSON equality.

Reconstruct only the deepest approximation, zeroing every detail coefficient.
Daubechies/Coiflet use the PyWavelets DWT convention (full convolution with
signal extension, odd samples kept; valid upsampled reconstruction). CDF uses
four lifting steps with approximation on odd original sample indices (zero
based). This phase is explicit: the unpadded PyWavelets default is a different
proposal. Native agreement is recorded separately in discovery.
"""
import argparse
import csv
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CASES = {
    "db2-symmetric": ("db2", "symmetric", 1),
    "db2-depth2": ("db2", "symmetric", 2),
    "db2-zero": ("db2", "zero", 1),
    "coif1-symmetric": ("coif1", "symmetric", 1),
    "cdf97-symmetric": ("cdf97", "symmetric", 1),
    "cdf97-reflect": ("cdf97", "reflect", 1),
}
# Agreement with the PyWavelets-generated expected is ~1e-14 with closed-form
# coefficients; 16-digit tabulated coif1 coefficients drift to ~2.4e-12, so the
# comparison is by tolerance, never by exact equality.
CHECK_TOLERANCE = 1e-10
assert 1e-11 <= CHECK_TOLERANCE <= 1e-8


def _closed_form_filters():
    s3, s7, r2 = math.sqrt(3), math.sqrt(7), math.sqrt(2)
    # Decomposition low-pass filters (convolution order), closed forms.
    db2 = [x / (4 * r2) for x in (1 - s3, 3 - s3, 3 + s3, 1 + s3)]
    coif1 = [x * r2 / 32 for x in (s7 - 3, 1 - s7, 14 - 2 * s7, 14 + 2 * s7, 5 + s7, 1 - s7)]
    return {"db2": db2, "coif1": coif1}


FILTERS = _closed_form_filters()


def check_orthonormal(name, h):
    assert abs(sum(h) - math.sqrt(2)) < 1e-15, name
    assert abs(sum(x * x for x in h) - 1) < 1e-15, name
    for shift in range(2, len(h), 2):
        assert abs(sum(h[k] * h[k + shift] for k in range(len(h) - shift))) < 1e-15, (name, shift)


def extended(values, index, mode):
    n = len(values)
    if 0 <= index < n:
        return values[index]
    if mode == "zero":
        return 0.0
    if mode == "symmetric":  # half-sample: x1 x0 | x0 x1 ... x(n-1) | x(n-1) x(n-2)
        index %= 2 * n
        return values[index if index < n else 2 * n - 1 - index]
    if mode == "reflect":  # whole-sample: x2 x1 | x0 x1 ... x(n-1) | x(n-2)
        index %= 2 * n - 2
        return values[index if index < n else 2 * n - 2 - index]
    raise ValueError(mode)


def dwt(values, dec_lo, dec_hi, mode):
    size = len(dec_lo)
    out = (len(values) + size - 1) // 2
    pick = lambda f: [sum(f[j] * extended(values, 2 * o + 1 - j, mode) for j in range(size)) for o in range(out)]
    return pick(dec_lo), pick(dec_hi)


def idwt(approximation, detail, rec_lo, rec_hi):
    size, n = len(rec_lo), len(approximation)
    result = []
    for o in range(2 * n - size + 2):
        m = o + size - 2
        result.append(sum(approximation[k] * rec_lo[m - 2 * k] + detail[k] * rec_hi[m - 2 * k]
                          for k in range(n) if 0 <= m - 2 * k < size))
    return result


def bank(name):
    dec_lo = FILTERS[name]
    rec_lo = dec_lo[::-1]
    rec_hi = [(-1) ** k * dec_lo[k] for k in range(len(dec_lo))]
    return dec_lo, rec_hi[::-1], rec_lo, rec_hi


def wavedec(values, name, mode, depth):
    dec_lo, dec_hi, rec_lo, rec_hi = bank(name)
    approximation, details = values, []
    for _ in range(depth):
        approximation, detail = dwt(approximation, dec_lo, dec_hi, mode)
        details.insert(0, detail)
    return approximation, details


def waverec(approximation, details, name):
    _, _, rec_lo, rec_hi = bank(name)
    for detail in details:
        if len(approximation) == len(detail) + 1:
            approximation = approximation[:-1]
        approximation = idwt(approximation, detail, rec_lo, rec_hi)
    return approximation


def pad(values, halo, mode):
    return [extended(values, i, mode) for i in range(-halo, len(values) + halo)]


def lifting(values, boundary, keep_detail):
    # Four lifting coefficients, independent of Loginom:
    # https://getreuer.info/posts/waveletcdf97/index.html
    alpha, beta = -1.586134342059924, -0.052980118572961
    gamma, delta = 0.882911075530934, 0.443506852043971
    # A depth-one analysis/synthesis stencil has radius <= 8. The odd halo
    # puts the approximation on original indices 1,3,...; its outer circular
    # accesses cannot reach the retained original interval. The phase holds
    # only for an odd halo (observation of this input, not a general claim).
    halo = 19
    assert halo % 2 == 1
    data = pad(values, halo, boundary)
    low, high = data[::2], data[1::2]
    assert len(low) == len(high)
    n = len(low)
    nxt = lambda a, i: a[(i + 1) % n]
    prv = lambda a, i: a[(i - 1) % n]
    high = [high[i] + alpha * (low[i] + nxt(low, i)) for i in range(n)]
    low = [low[i] + beta * (prv(high, i) + high[i]) for i in range(n)]
    high = [high[i] + gamma * (low[i] + nxt(low, i)) for i in range(n)]
    low = [low[i] + delta * (prv(high, i) + high[i]) for i in range(n)]
    # Forward/inverse normalizations cancel for the retained approximation.
    if not keep_detail:
        high = [0.0] * n
    low = [low[i] - delta * (prv(high, i) + high[i]) for i in range(n)]
    high = [high[i] - gamma * (low[i] + nxt(low, i)) for i in range(n)]
    low = [low[i] - beta * (prv(high, i) + high[i]) for i in range(n)]
    high = [high[i] - alpha * (low[i] + nxt(low, i)) for i in range(n)]
    reconstructed = [0.0] * (2 * n)
    reconstructed[::2], reconstructed[1::2] = low, high
    return reconstructed[halo:-halo]


def smooth(values, case):
    name, boundary, depth = CASES[case]
    if name == "cdf97":
        # Perfect reconstruction of the lifting scheme is a numerical sanity check.
        assert max(abs(a - b) for a, b in zip(lifting(values, boundary, True), values, strict=True)) < 1e-9
        return lifting(values, boundary, False)
    approximation, details = wavedec(values, name, boundary, depth)
    # Full reconstruction is an independent numerical sanity check; it does
    # not establish Loginom's phase, padding length, or filter normalization.
    full = waverec(approximation, details, name)[:len(values)]
    assert max(abs(a - b) for a, b in zip(full, values, strict=True)) < 1e-9
    return waverec(approximation, [[0.0] * len(d) for d in details], name)[:len(values)]


def expected(case):
    with (ROOT / "fixtures" / "wavelet.csv").open(newline="", encoding="utf-8") as source:
        rows = [{"RowID": int(r["RowID"]), "X": int(r["X"]), "Tag": r["Tag"]}
                for r in csv.DictReader(source)]
    values = [float(r["X"]) for r in rows]
    smoothed = smooth(values, case)
    assert all(math.isfinite(v) for v in smoothed)
    assert max(abs(a - b) for a, b in zip(smoothed, values)) > 0.1, "Nondegenerate fixture required"
    for row, value in zip(rows, smoothed, strict=True):
        row["X_S"] = value
    return {"package_path": "{{PACKAGE_PATH}}", "null_marker": "?",
            "nodes": [{"type": t} for t in ("imports.text", "preprocessing.smoothing", "exports.text")],
            "outputs": [{"output_node_type": "preprocessing.smoothing", "output_port": 0,
                         "ordered": True, "column_order": "exact",
                         "columns": [{"name": name, "type": kind, "label_any": True,
                                      **({"tolerance": {"abs": 1e-8, "rel": 1e-10}} if kind == "real" else {})}
                                     for name, kind in (("RowID", "integer"), ("X", "integer"),
                                                        ("Tag", "string"), ("X_S", "real"))],
                         "rows": rows}]}


def matches(stored, computed):
    """Everything equal except X_S, which must agree within CHECK_TOLERANCE."""
    left, right = json.loads(json.dumps(stored)), json.loads(json.dumps(computed))
    a_rows, b_rows = left["outputs"][0].pop("rows"), right["outputs"][0].pop("rows")
    if left != right or len(a_rows) != len(b_rows):
        return False
    for a, b in zip(a_rows, b_rows):
        if {k: v for k, v in a.items() if k != "X_S"} != {k: v for k, v in b.items() if k != "X_S"}:
            return False
        if abs(a["X_S"] - b["X_S"]) > CHECK_TOLERANCE:
            return False
    return True


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, h in FILTERS.items():
        check_orthonormal(name, h)
    results = {}
    for case in CASES:
        result = expected(case)
        results[case] = [r["X_S"] for r in result["outputs"][0]["rows"]]
        path = Path(__file__).parent / ("expected-" + case + ".json")
        if args.write:
            path.write_text(json.dumps(result, ensure_ascii=False, indent=2, allow_nan=False) + "\n", encoding="utf-8")
        if args.check:
            assert matches(json.loads(path.read_text(encoding="utf-8")), result), path.name
    for left, right in (("db2-symmetric", "coif1-symmetric"),
                        ("db2-symmetric", "cdf97-symmetric"),
                        ("db2-symmetric", "db2-depth2"),
                        ("db2-symmetric", "db2-zero"),
                        ("cdf97-symmetric", "cdf97-reflect")):
        assert max(abs(a - b) for a, b in zip(results[left], results[right])) > 0.01, (left, right)
    print("Six independent nondegenerate filter proposals reproduced (stdlib, tolerance %g); "
          "consult discovery before acceptance." % CHECK_TOLERANCE)
