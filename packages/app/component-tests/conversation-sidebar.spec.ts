import { expect, sourceURL, story } from "../../stories/playwright/story"

const fixture = sourceURL(new URL("../../gui-plugins/src/loginom-gui/sidebar.fixture.tsx", import.meta.url))

story(
  "project folders expand independently, reveal six conversations, and show pending activity",
  async ({ mount, page }) => {
    await mount("ui-line-comment--editor")
    await page.evaluate(async (url) => (await import(url)).mountSidebar(), fixture)
    const projects = page.getByRole("region", { name: "projects" })
    const conversations = page.getByRole("region", { name: "conversations" })
    const reports = projects.getByRole("button", { name: /^Отчёты/ })
    const other = projects.getByRole("button", { name: "Другой проект" })
    await expect(reports.getByRole("img", { name: "conversationWaiting" })).toBeVisible()
    await expect(conversations.getByRole("img", { name: "conversationRunning" })).toBeVisible()
    await expect(projects.getByText("Разговор без проекта")).toHaveCount(0)
    await expect(conversations.getByText("Отчёт 1")).toHaveCount(0)

    await reports.click()
    await other.click()
    await expect(reports).toHaveAttribute("aria-expanded", "true")
    await expect(other).toHaveAttribute("aria-expanded", "true")
    await expect(projects.getByText(/^Отчёт \d+$/)).toHaveCount(6)
    await expect(projects.getByText(/^Отчёт \d+$/).first()).toHaveText("Отчёт 8")
    await expect(projects.getByText("Отчёт 2")).toHaveCount(0)
    await projects.getByRole("button", { name: "showMoreConversations" }).click()
    const latest = projects.getByRole("button", { name: /^Отчёт 8/ })
    await expect(projects.getByText("Отчёт 2")).toBeVisible()
    await expect(projects.getByRole("button", { name: "showMoreConversations" })).toHaveCount(0)
    await expect(latest.getByRole("img")).toHaveCount(0)
    await latest.click()
    await expect(page.locator("[data-opened]")).toHaveAttribute("data-opened", "report-7")
    await page.evaluate(() => document.dispatchEvent(new Event("sidebar-refresh")))
    await expect(latest).toBeFocused()
    await conversations.getByRole("button", { name: /^Разговор без проекта/ }).click()
    await expect(page.locator("[data-opened]")).toHaveAttribute("data-opened", "loose")
    await reports.click()
    await expect(other).toHaveAttribute("aria-expanded", "true")
    await expect(projects.getByText("Отчёт 1")).toHaveCount(0)
  },
)

story("project creation preserves the entered name when retrying an error", async ({ mount, page }) => {
  await mount("ui-line-comment--editor")
  await page.evaluate(async (url) => (await import(url)).mountSidebar(), fixture)
  await page.getByRole("button", { name: "newProject" }).click()
  const name = page.getByRole("textbox", { name: "projectName" })
  const create = page.getByRole("button", { name: "createProject" })
  await name.fill("Отчёт: Q1/Q2")
  await create.click()
  await expect(page.getByRole("alert")).toHaveText("projectCreateFailed")
  await expect(name).toHaveValue("Отчёт: Q1/Q2")
  await create.click()
  await expect(name).toHaveCount(0)
  await expect(page.locator("[data-created]")).toHaveAttribute("data-created", "Отчёт: Q1/Q2")
})

story("a hung project save times out and lets the user retry or cancel", async ({ mount, page }) => {
  await mount("ui-line-comment--editor")
  await page.clock.install()
  await page.evaluate(async (url) => (await import(url)).mountSidebar("timeout"), fixture)
  await page.getByRole("button", { name: "newProject" }).click()
  const name = page.getByRole("textbox", { name: "projectName" })
  const create = page.getByRole("button", { name: "createProject" })
  await name.fill("Отчёт")
  await create.click()
  await expect(create).toBeDisabled()
  await page.clock.fastForward(15_500)
  await expect(page.getByRole("alert")).toHaveText("projectCreateTimedOut")
  await expect(name).toHaveValue("Отчёт")
  await create.click()
  await page.getByRole("button", { name: "cancelProject" }).click()
  await expect(name).toHaveCount(0)
})
