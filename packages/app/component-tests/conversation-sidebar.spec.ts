import { expect, sourceURL, story } from "../../stories/playwright/story"

const fixture = sourceURL(new URL("./conversation-sidebar.fixture.tsx", import.meta.url))

story(
  "project folders expand independently, reveal six conversations, and show pending activity",
  async ({ mount, page }) => {
    await mount("ui-line-comment--editor")
    await page.evaluate(async (url) => (await import(url)).mountSidebar(), fixture)
    const projects = page.getByRole("region", { name: "projects" })
    const conversations = page.getByRole("region", { name: "conversations" })
    const reports = projects.getByRole("button", { name: /^Отчёты/ })
    const other = projects.getByRole("button", { name: "Другой проект", exact: true })
    await expect(reports.getByRole("img", { name: "conversationWaiting" })).toBeVisible()
    await expect(projects.getByText("Разговор без проекта")).toHaveCount(0)
    await expect(conversations.getByText("Отчёт 1")).toHaveCount(0)

    await reports.click()
    await other.click()
    await expect(reports).toHaveAttribute("aria-expanded", "true")
    await expect(other).toHaveAttribute("aria-expanded", "true")
    await expect(projects.getByText(/^Отчёт \d+$/)).toHaveCount(6)
    await expect(projects.getByText("Отчёт 6")).toBeVisible()
    await projects.getByRole("button", { name: "showMoreConversations" }).click()
    const latest = projects.getByRole("button", { name: /^Отчёт 8/ })
    await expect(latest.getByRole("img", { name: "conversationWaiting" })).toBeVisible()
    await latest.click()
    await expect(page.locator("[data-opened]")).toHaveAttribute("data-opened", "report-7")
    await conversations.getByRole("button", { name: /^Разговор без проекта/ }).click()
    await expect(page.locator("[data-opened]")).toHaveAttribute("data-opened", "loose")
    await reports.click()
    await expect(other).toHaveAttribute("aria-expanded", "true")
    await expect(projects.getByText("Отчёт 1")).toHaveCount(0)
  },
)

story("conversation and project menus expose actions and confirmations", async ({ mount, page }) => {
  await mount("ui-line-comment--editor")
  await page.evaluate(async (url) => (await import(url)).mountSidebar(), fixture)
  const sandbox = page.locator("nav").locator("..")
  const action = (title: string) => page.getByRole("button", { name: `actions — ${title}`, exact: true })
  const item = (name: string) => page.getByRole("menuitem", { name, exact: true })
  const loose = "Разговор без проекта"
  const pinned = page.getByRole("region", { name: "pinned" })
  await expect(pinned).toHaveCount(0)

  await action(loose).click()
  await item("rename").click()
  let prompt = page.getByRole("dialog")
  await prompt.getByRole("textbox").fill("Переименованный")
  await prompt.getByRole("button", { name: "save" }).click()
  await expect(sandbox).toHaveAttribute("data-renamed", "loose:Переименованный")

  await action(loose).click()
  await item("move").click()
  await item("Другой проект").click()
  await expect(sandbox).toHaveAttribute("data-moved", "loose:/other")
  await expect(page.getByRole("button", { name: "Другой проект", exact: true })).toHaveAttribute("aria-expanded", "true")

  await action(loose).click()
  await item("move").click()
  await item("moveNew").click()
  prompt = page.getByRole("dialog")
  await prompt.getByRole("textbox").fill("Новый")
  await prompt.getByRole("button", { name: "createProject" }).click()
  await expect(sandbox).toHaveAttribute("data-moved", "loose:Новый")

  await page.getByRole("button", { name: /^Отчёты/ }).click()
  await action("Отчёт 2").click()
  await item("detach").click()
  await expect(sandbox).toHaveAttribute("data-moved", "report-1:/loose")

  await action("Отчёт 2").click()
  await item("pin").click()
  await expect(pinned.getByRole("button", { name: "Отчёт 2 Отчёты" })).toBeVisible()
  await expect(page.getByRole("region", { name: "projects" }).getByText("Отчёт 2", { exact: true })).toHaveCount(0)
  await action("Отчёт 2").click()
  await item("unpin").click()
  await expect(pinned).toHaveCount(0)

  await action("Отчёты").click()
  await item("pin").click()
  await expect(pinned.getByRole("button", { name: "Отчёты", exact: true })).toBeVisible()
  await action("Отчёты").click()
  await item("projectSettings").click()
  await expect(sandbox).toHaveAttribute("data-settings", "/reports")
  await action("Отчёты").click()
  await item("deleteProject").click()
  await prompt.getByRole("button", { name: "cancelProject" }).click()
  await expect(sandbox).not.toHaveAttribute("data-deleted-project")
  await action("Отчёты").click()
  await item("deleteProject").click()
  await prompt.getByRole("button", { name: "deleteProject" }).click()
  await expect(sandbox).toHaveAttribute("data-deleted-project", "/reports")

  for (const checkbox of [false, true]) {
    await action(loose).click()
    await item("deleteConversation").click()
    const files = prompt.getByRole("checkbox")
    await expect(files).not.toBeChecked()
    if (checkbox) await files.check()
    await prompt.getByRole("button", { name: "deleteConversation" }).click()
    await expect(sandbox).toHaveAttribute("data-deleted", `loose:${checkbox}`)
  }
})
