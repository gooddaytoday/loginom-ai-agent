import test from 'node:test';
import assert from 'node:assert/strict';
import {validateGroupingParameters,resolveGroupingParameters} from '../lib/grouping-parameters.mjs';
import {groupingMeasureSchema} from '../lib/node-api.mjs';
import {configureGrouping} from '../lib/grouping-procedure.mjs';
import {groupingOutputDefinitions,resolveGroupingOutput} from '../lib/grouping-output.mjs';

const field=name=>({kind:'input_field',name});
const measure=(name,fn,output)=>({field:field(name),function:fn,name:output,label:output});
const request={target:{kind:'new'},inputs:[{input:0}],read:{ports:[0]},mappings:[],finish:'execute'};
const parameters={group_by:[field('Region')],measures:[measure('Customer','count','Rows'),measure('Customer','unique_count','UniqueCustomers'),measure('CustomerId','unique_count','UniqueIds')]};
const fields=[{name:'Region',type:'string'},{name:'Customer',type:'string'},{name:'CustomerId',type:'integer'}];
const configuration={keys:[{name:'Region',label:'Region',type:'string'}],measures:[
 {name:'Customer',label:'Customer',type:'string',functions:258},
 {name:'CustomerId',label:'CustomerId',type:'integer',functions:256}]};

test('Grouping unique_count is advertised and resolves string/integer with count',()=>{
 assert.ok(groupingMeasureSchema.properties.function.enum.includes('unique_count'));
 validateGroupingParameters(parameters,'aggregate',request);
 assert.deepEqual(resolveGroupingParameters(parameters,fields).functions,[{name:'Customer',mask:258},{name:'CustomerId',mask:256}]);
 for(const type of ['real','boolean','datetime','variant']){
  assert.throws(()=>resolveGroupingParameters(parameters,fields.map(f=>f.name==='CustomerId'?{...f,type}:f)),/incompatible/);
 }
 for(const fn of ['median','mode','stddev','list','null_count']){
  assert.throws(()=>validateGroupingParameters({...parameters,measures:[measure('Customer',fn,'Bad')]},'aggregate',request));
 }
 assert.throws(()=>validateGroupingParameters({...parameters,measures:[...parameters.measures,measure('Customer','unique_count','Duplicate')]},'aggregate',request),/Duplicate field\/function/);
});

// Native Grouping uses Uniq, not CrossTable's UniqueCount. These source names,
// labels and types are independent observations, not generated by the resolver.
const sources=[
 {record_id:'s0',name:'Region',label:'Region',type:'string'},
 {record_id:'s1',name:'Customer_Count',label:'Customer|Количество',type:'integer'},
 {record_id:'s2',name:'Customer_Uniq',label:'Customer|Кол-во уникальных',type:'integer'},
 {record_id:'s3',name:'CustomerId_Uniq',label:'CustomerId|Кол-во уникальных',type:'integer'}];
const native=()=>({verified:true,inventory_complete:true,source_identity_verified:true,mapping_wizard:'DerivedDataSourceOutputSocketWizard',source_fields:structuredClone(sources),
 target_fields:sources.map((s,i)=>({...s,record_id:'t'+i,name:i===3?'CustomerId':s.name,source:structuredClone(s),inherited:false,excluded:false}))});
test('Grouping unique_count output binds Uniq integer sources and renames mixed/single functions',()=>{
 assert.deepEqual(groupingOutputDefinitions(configuration).map(f=>[f.name,f.type]),[['Region','string'],['Customer_Count','integer'],['Customer_Uniq','integer'],['CustomerId','integer']]);
 const resolved=resolveGroupingOutput(configuration,parameters,native());
 assert.deepEqual(resolved.fields.map(f=>[f.source.name,f.name,f.current.type]),[['Region','Region','string'],['Customer_Count','Rows','integer'],['Customer_Uniq','UniqueCustomers','integer'],['CustomerId_Uniq','UniqueIds','integer']]);
 const saved=native();saved.target_fields[2].name='SavedName';saved.target_fields[2].label='Saved label';
 assert.deepEqual(resolveGroupingOutput(configuration,{},saved),{fields:null});
 for(const change of [n=>n.source_fields[2].name='Customer_UniqueCount',n=>n.source_fields[2].type='string',n=>n.target_fields[2].source=n.source_fields[1]]){
  const n=native();change(n);assert.throws(()=>resolveGroupingOutput(configuration,parameters,n));
 }
});

test('Grouping preserves saved unique_count masks, refusing all other new bits and types',async()=>{
 const channel=c=>({observe:async options=>{const s={wizard:{stage:'grouping'},node_grouping:{...c,verified:true}};assert.ok(options.ready(s));return s;},perform:()=>assert.fail('preservation must not mutate')});
 const saved=await configureGrouping(channel(configuration),{});
 assert.equal(saved.preservation.unchanged,true);
 for(const bit of [32,64,128,512,1024,2048,4096,8192]){
  const c=structuredClone(configuration);c.measures[0].functions|=bit;
  await assert.rejects(configureGrouping(channel(c),{}),/unsupported/);
  assert.throws(()=>groupingOutputDefinitions(c),/Unsupported/);
 }
 const c=structuredClone(configuration);c.measures[1].type='real';
 await assert.rejects(configureGrouping(channel(c),{}),/unsupported/);
 assert.throws(()=>groupingOutputDefinitions(c),/Unsupported/);
});
